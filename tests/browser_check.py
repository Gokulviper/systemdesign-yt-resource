"""Browser smoke test for every page plus deep interaction checks on lab pages.
Run: python3 tests/browser_check.py  (needs: pip install playwright && playwright install chromium)
Pages are opened over file:// exactly as a user would open them."""
import pathlib, sys, json
from playwright.sync_api import sync_playwright

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHOTS = ROOT / "tests" / "screenshots"
SHOTS.mkdir(exist_ok=True)
failures = []

def check(cond, msg):
    print(("  ok   " if cond else "  FAIL ") + msg)
    if not cond: failures.append(msg)

def lab_state(page, expr):
    return page.evaluate(f"(() => {{ const {{sim, ctl}} = window.SDL_LAB; return {expr}; }})()")

def run_until_idle(page, limit=20000):
    page.evaluate(f"window.SDL_LAB.sim.runUntilIdle({limit})")
    page.wait_for_timeout(350)

with sync_playwright() as p:
    browser = p.chromium.launch()
    ctx = browser.new_context(viewport={"width": 1440, "height": 1000})
    page = ctx.new_page()
    errors = []
    page.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
    page.on("pageerror", lambda e: errors.append(str(e)))
    # Fonts come from Google; block them so tests are deterministic offline.
    page.route("**/fonts.googleapis.com/**", lambda r: r.abort())
    page.route("**/fonts.gstatic.com/**", lambda r: r.abort())
    def real_errors(): return [e for e in errors if "fonts.g" not in e and "ERR_FAILED" not in e]

    print("All pages load without errors and have working navigation")
    htmls = sorted(ROOT.rglob("*.html"))
    htmls = [h for h in htmls if "tests" not in h.parts]
    for h in htmls:
        errors.clear()
        page.goto(h.as_uri())
        page.wait_for_timeout(120)
        title = page.title()
        hdr = page.locator(".site-header").count()
        links = page.eval_on_selector_all(".topic-menu a", "els => els.map(a => a.href)")
        expected = page.evaluate("SDL.PAGES.length")
        missing = [l for l in links if not pathlib.Path(l.replace("file://", "")).exists()]
        check(hdr == 1 and not real_errors() and not missing and len(links) == expected,
              f"{h.relative_to(ROOT)}: '{title}' errors={real_errors()} broken_links={missing}")

    print("\nSandbox lab")
